// Reproduce the offline parser from the versions installed by pnpm-lock.yaml.
// Only emoji-data's regex is used; no emoji keyword data or artwork is bundled.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ios = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(join(ios, '../../packages/frontend/package.json'));
const mfmRoot = dirname(dirname(require.resolve('mfm-js')));
const mfmRequire = createRequire(join(mfmRoot, 'package.json'));
const emojiRoot = dirname(dirname(mfmRequire.resolve('@misskey-dev/emoji-data')));
const mfm = JSON.parse(readFileSync(join(mfmRoot, 'package.json'), 'utf8'));
const emoji = JSON.parse(readFileSync(join(emojiRoot, 'package.json'), 'utf8'));
const directory = join(ios, 'Core/Sources/GridSpaceCore/Resources/MFM');
const outputs = new Map();
outputs.set('Parser.js', `// Generated by apps/ios/scripts/build-mfm.mjs. Do not edit.
// mfm-js ${mfm.version}; @misskey-dev/emoji-data ${emoji.version} (regex only).
// Third-party MIT notices are distributed alongside this file.
(function () {
"use strict";
const emoji = {};
(function (exports) {
${readFileSync(join(emojiRoot, 'built/regex.cjs'), 'utf8')}
})(emoji);
const mfm = {};
(function (exports, require) {
${readFileSync(join(mfmRoot, 'built/index.cjs'), 'utf8')}
})(mfm, function (name) {
    if (name === "@misskey-dev/emoji-data") return emoji;
    throw new Error("No module access");
});
globalThis.gridspaceParseMFM = function (text) {
    return JSON.stringify(mfm.parse(text, { nestLimit: 20 }));
};
})();
`);
for (const [name, source] of [
	['LICENSE-mfm-js.txt', join(mfmRoot, 'LICENSE')],
	['LICENSE-emoji-data.txt', join(emojiRoot, 'LICENSE')],
	['LICENSE-emoji-code.txt', join(emojiRoot, 'LICENSE-CODE')],
	['LICENSE-emoji-regex.txt', join(emojiRoot, 'LICENSE-TWEMOJI-PARSER')],
]) outputs.set(name, readFileSync(source, 'utf8').replace(/[ \t]+$/gm, ''));

const examples = [
	'plain\r\n日本語 👨‍👨‍👧‍👧 :synthetic: **bold <i>nested</i>** ~~strike~~ <small>small</small>',
	'> quote\n> **nested**\n\n<center>center\nline</center>',
	'@alice @bob@remote.example #タグ https://example.test/path?a=1&b=2 [label **bold**](https://example.test) ?[silent](https://example.test)',
	'`let x = 1`\n```swift\nlet x = "space  ";\n\nprint(x)\n```',
	'<plain>**literal** :emoji: @alice</plain> \\(x^2\\)\n\\[\nx^2\n\\]',
	'$[blur secret :synthetic:] $[fg.color=abc foreground] $[bg.color=123456 background] $[font.monospace mono] $[x2 large]',
	'$[ruby 漢字 かんじ] $[spin.left,speed=2s animated] $[unknown.arg=yes child] $[clickable.ev=event click]',
	'"; globalThis.notExecuted = true; // <script>alert(1)</script> [bad](javascript:alert(1))',
];
const parser = mfmRequire('./built/index.cjs');
const fixtures = examples.map(text => ({ text, nodes: parser.parse(text, { nestLimit: 20 }) }));
const fixturePath = join(ios, 'Core/Tests/GridSpaceCoreTests/Resources/MFMFixtures.json');
const fixture = JSON.stringify({ mfmVersion: mfm.version, emojiVersion: emoji.version, fixtures }, null, 2) + '\n';
const check = process.argv.includes('--check');
for (const [path, contents] of [...Array.from(outputs, ([name, contents]) => [join(directory, name), contents]), [fixturePath, fixture]]) {
	if (check) {
		if (readFileSync(path, 'utf8') !== contents) throw new Error('Stale MFM resource: ' + path);
	} else {
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, contents);
	}
}
console.log(`MFM resources ${check ? 'verified' : 'generated'}: ${mfm.version} / emoji regex ${emoji.version}`);
