// Bundle the same Unicode definitions as the Web picker, with Japanese search
// annotations. Native system glyphs supply the artwork; no artwork is copied.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ios = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(join(ios, '../../packages/frontend/package.json'));
const root = dirname(dirname(require.resolve('@misskey-dev/emoji-data')));
const entries = JSON.parse(readFileSync(join(root, 'built/emojilist.json'), 'utf8'));
const ja = JSON.parse(readFileSync(join(root, 'built/indexes/ja-JP.json'), 'utf8'));
const hira = JSON.parse(readFileSync(join(root, 'built/indexes/ja-JP_hira.json'), 'utf8'));
const catalog = entries.map(([char, name, category]) => ({ char, name, category, keywords: [...new Set([...(ja[char] ?? []), ...(hira[char] ?? [])])] }));
const directory = join(ios, 'Core/Sources/GridSpaceCore/Resources/Emoji');
const outputs = new Map([['catalog.json', JSON.stringify(catalog) + '\n']]);
for (const name of ['LICENSE', 'LICENSE-CODE', 'LICENSE-EMOJILIB', 'LICENSE-CLDR']) outputs.set(name + '.txt', readFileSync(join(root, name), 'utf8').replace(/[ \t]+$/gm, ''));
outputs.set('SOURCE.txt', `Generated by apps/ios/scripts/build-emoji.mjs from @misskey-dev/emoji-data ${JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version}.\nUnicode definitions and Japanese annotation keywords only; no third-party artwork.\n`);
for (const [name, contents] of outputs) {
	const path = join(directory, name);
	if (process.argv.includes('--check')) { if (readFileSync(path, 'utf8') !== contents) throw new Error('Stale emoji resource: ' + path); }
	else { mkdirSync(directory, { recursive: true }); writeFileSync(path, contents); }
}
console.log(`Unicode emoji catalog verified: ${catalog.length} entries`);
